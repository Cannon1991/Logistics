# Database connection parameters
conn_params = {
    "host": "localhost",
    "database": "logistics_db",
    "user": "postgres",
    "password": "securepassword",
    "port": 5432
}

try:
    conn = psycopg2.connect(**conn_params)

    # Query to calculate density metrics for Abuja (FC) and Port Harcourt (RV) using PostGIS spatial functions
    # We measure density as the number of orders divided by the area of their Minimum Bounding Box (Envelope) in square kilometers
    density_query = """
        SELECT
            CASE postcode_state
                WHEN 'FC' THEN 'Abuja (AMAC / Maitama)'
                WHEN 'RV' THEN 'Port Harcourt (GRA Phase 2)'
            END AS cluster_name,
            COUNT(*) AS total_orders,
            -- Area of minimum bounding envelope converted to square kilometers
            ROUND((ST_Area(ST_Envelope(ST_Collect(coordinates))::geography) / 1000000.0)::numeric, 2) AS area_sq_km,
            -- Density = orders per square kilometer
            ROUND((
                COUNT(*) / NULLIF(ST_Area(ST_Envelope(ST_Collect(coordinates))::geography) / 1000000.0, 0)
            )::numeric, 2) AS orders_per_sq_km
        FROM shipping_orders
        WHERE postcode_state IN ('FC', 'RV')
        GROUP BY postcode_state;
    """

    df = pd.read_sql_query(density_query, conn)
    conn.close()

    print("📊 Delivery Density Analysis:")
    display(df)

except Exception as error:
    print("❌ Spatial density calculation failed:", error)

