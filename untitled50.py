from sqlalchemy import create_engine
import pandas as pd

try:
    # Initialize SQLAlchemy connection engine
    engine = create_engine("postgresql+psycopg2://postgres:securepassword@localhost:5432/logistics_db")

    # Spatial query to calculate distance between Abuja and Port Harcourt centroids
    centroid_distance_query = """
        WITH regional_centroids AS (
            SELECT
                postcode_state,
                ST_Centroid(ST_Collect(coordinates)) AS centroid
            FROM shipping_orders
            WHERE postcode_state IN ('FC', 'RV')
            GROUP BY postcode_state
        )
        SELECT
            ST_Distance(
                (SELECT centroid::geography FROM regional_centroids WHERE postcode_state = 'FC'),
                (SELECT centroid::geography FROM regional_centroids WHERE postcode_state = 'RV')
            ) AS distance_meters;
    """

    # Execute the query
    df_distance = pd.read_sql_query(centroid_distance_query, engine)
    distance_m = df_distance['distance_meters'].iloc[0]
    distance_km = distance_m / 1000.0

    print("📊 Centroid Spatial Distance Analysis:")
    print(f"- Ellipsoidal Distance: {distance_m:,.2f} meters")
    print(f"- Ellipsoidal Distance: {distance_km:,.2f} km")

except Exception as error:
    print("❌ Failed to compute centroid distances:", error)

