    engine = create_engine("postgresql+psycopg2://postgres:securepassword@localhost:5432/logistics_db")

    # Fetch coordinates and properties for both clusters
    map_query = """
        SELECT
            tracking_number,
            order_status,
            nipost_postcode,
            street_address,
            postcode_state,
            ST_AsText(coordinates) AS coordinates_wkt
        FROM shipping_orders
        WHERE postcode_state IN ('FC', 'RV')
        LIMIT 100; -- Pull balanced sample points for clean rendering
    """
    df_map = pd.read_sql_query(map_query, engine)

    # Parser helper function
    def extract_coords(wkt_str):
        if wkt_str:
            point = wkt.loads(wkt_str)
            return point.y, point.x
        return None, None

    df_map['lat'], df_map['lng'] = zip(*df_map['coordinates_wkt'].apply(extract_coords))

    # Compute center dynamically to scale/focus the canvas properly between Abuja & Port Harcourt
    # (We will center near the geographic midpoint of the data)
    center_lat = df_map['lat'].mean()
    center_lng = df_map['lng'].mean()

    # Initialize Folium Map
    m_nigeria = folium.Map(location=[center_lat, center_lng], zoom_start=6, tiles='OpenStreetMap')

    # Use distinct color markers to segment territories
    # Blue: Abuja (FC), Purple: Port Harcourt (RV)
    for idx, row in df_map.iterrows():
        if pd.notnull(row['lat']) and pd.notnull(row['lng']):
            color = 'blue' if row['postcode_state'] == 'FC' else 'purple'
            region_name = 'Abuja (AMAC)' if row['postcode_state'] == 'FC' else 'Port Harcourt (GRA)'
