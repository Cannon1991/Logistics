STATUS_CHOICES = ['pending', 'processing', 'in-transit', 'delivered']

def generate_mock_orders(batch_size=10000):
    print(f"📦 Simulating {batch_size} realistic structural order matrices for Nigeria...")
    orders = []

    for i in range(batch_size):
        # Pick a regional hub cluster
        cluster = random.choice(NIGERIAN_CLUSTERS)

        # Structure the Building sequential ID (3 digits trailing: e.g., 001 to 999)
        building_num = random.randint(1, 999)
        building_suffix = f"{building_num:03d}"

        # Build clean 11-digit string matching regex structure: ^[A-Z0-9]{11}$
        raw_postcode = f"{cluster['state_code']}{cluster['lga_code']}{cluster['district_code']}{cluster['area_code']}{building_suffix}"

        # Inject randomized micro-variance to geographic points within the area
        lat_offset = random.uniform(-0.008, 0.008)
        lng_offset = random.uniform(-0.008, 0.008)
        final_lat = cluster['base_lat'] + lat_offset
        final_lng = cluster['base_lng'] + lng_offset

        tracking_num = f"NG-LOG-{random.randint(100000, 999999)}-{i}"
        cust_id = str(uuid.uuid4())
        status = random.choices(STATUS_CHOICES, weights=[20, 40, 30, 10])[0]
        apt_unit = f"Suite {random.randint(1, 25)}, Floor {random.randint(1, 4)}"
        full_street = f"Structure Node {building_suffix}, {cluster['street']}, Nigeria"

        # Coordinates structured as Well-Known Text (WKT) for native PostGIS insertions
        wkt_point = f"SRID=4326;POINT({final_lng} {final_lat})"

        orders.append((
            tracking_num,
            cust_id,
            status,
            raw_postcode,
            apt_unit,
            full_street,
            wkt_point
        ))

    return orders

